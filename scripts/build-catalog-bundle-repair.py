#!/usr/bin/env python3
"""Build the guarded bundle restoration from the repository's original layouts.

Only template furniture/room rows are read from CleanDB.sql. No users, credentials,
inventories, or unrelated database contents are copied.
"""
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Database/Default Database/CleanDB.sql"
TARGET = ROOT / "Emulator/src/main/resources/db/migration/V20261020191000__restore_stock_room_bundle_templates.sql"


def rows(table):
    active = False
    columns = []
    for line in SOURCE.read_text().splitlines():
        if line.startswith(f"INSERT INTO `{table}` ("):
            columns = [c.strip(" `") for c in line.split("(", 1)[1].split(")", 1)[0].split(",")]
            active = True
            continue
        if active and line.lstrip().startswith("("):
            row = line.strip().rstrip(",;")[1:-1]
            values = next(csv.reader([row], delimiter=",", quotechar="'", escapechar="\\", skipinitialspace=True))
            assert len(columns) == len(values), (table, line)
            yield dict(zip(columns, values))
            if line.rstrip().endswith(";"):
                active = False


def q(value):
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def generate():
    definitions = {int(r["id"]): r["item_name"] for r in rows("items_base")}
    rooms = {int(r["id"]): r for r in rows("rooms") if 50 <= int(r["id"]) <= 56}
    placements = [r for r in rows("items") if 50 <= int(r["room_id"]) <= 56]
    assert len(placements) == 335 and len(rooms) == 7
    counts = Counter(int(r["room_id"]) for r in placements)
    captions = ["dark_elegant_20", "chill_modern_20", "pigglets_habitat20", "polarbear_habitat20", "cat_habitat20", "puppy_habitat20", "terrier_habitat20"]
    sql = ["""-- Generated by scripts/build-catalog-bundle-repair.py from CleanDB.sql.
-- Restore the seven original layouts into NEW rooms. Existing rooms, inventories,
-- offer prices, badge extras, limited sales and customized bundles are preserved.
CREATE TABLE IF NOT EXISTS catalog_bundle_repair_20261020 (
    page_id INT PRIMARY KEY,
    previous_room_id INT NOT NULL,
    offer_id INT NOT NULL,
    previous_item_ids VARCHAR(666) NOT NULL,
    room_id INT NOT NULL DEFAULT 0,
    items_restored TINYINT NOT NULL DEFAULT 0
);
CREATE TEMPORARY TABLE catalog_bundle_source_20261020 (
    page_id INT NOT NULL, item_name VARCHAR(255) NOT NULL,
    wall_pos VARCHAR(20) NOT NULL, x INT NOT NULL, y INT NOT NULL,
    z DOUBLE NOT NULL, rot INT NOT NULL, extra_data VARCHAR(1024) NOT NULL
);
INSERT INTO catalog_bundle_source_20261020
    (page_id, item_name, wall_pos, x, y, z, rot, extra_data) VALUES"""]
    values = []
    for r in placements:
        page = int(r["room_id"]) + 950
        name = definitions[int(r["item_id"])]
        values.append(f"({page}, {q(name)}, {q(r['wall_pos'])}, {r['x']}, {r['y']}, {r['z']}, {r['rot']}, {q(r['extra_data'])})")
    sql.append(",\n".join(values) + ";")
    sql.append("""
SET @bundle_owner_id = (SELECT MIN(id) FROM users WHERE `rank` >= 7);
SET @bundle_owner_name = (SELECT username FROM users WHERE id = @bundle_owner_id);
""")
    for index, caption in enumerate(captions):
        page, old_room, offer, sentinel, badge = 1000 + index, 50 + index, 11048 + index, 59972 + index, 50200 + index
        r = rooms[old_room]
        sql.append(f"""
-- {r['name']}: {counts[old_room]} original placements.
INSERT IGNORE INTO catalog_bundle_repair_20261020
    (page_id, previous_room_id, offer_id, previous_item_ids)
SELECT p.id, p.room_id, c.id, c.item_ids
FROM catalog_pages p JOIN catalog_items c ON c.page_id = p.id
WHERE p.id = {page} AND p.caption_save = {q(caption)} AND p.page_layout = 'room_bundle'
  AND p.room_id = {old_room} AND c.id = {offer} AND c.item_ids = '{sentinel}'
  AND c.extradata = '{badge}' AND c.limited_stack = 0 AND c.limited_sells = 0
  AND @bundle_owner_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM items_base WHERE id = {sentinel})
  AND EXISTS (SELECT 1 FROM items_base WHERE id = {badge} AND type = 'b')
  AND EXISTS (SELECT 1 FROM room_models WHERE name = {q(r['model'])})
  AND NOT EXISTS (
      SELECT 1 FROM catalog_bundle_source_20261020 s
      LEFT JOIN items_base i ON i.item_name = s.item_name
      WHERE s.page_id = p.id AND i.id IS NULL
  );

INSERT INTO rooms (owner_id, owner_name, name, description, model, state, users_max,
                   category, paper_floor, paper_wall, paper_landscape,
                   thickness_wall, wall_height, thickness_floor, moodlight_data, tags, allow_hidewall)
SELECT @bundle_owner_id, @bundle_owner_name, {q(r['name'])}, {q(r['description'])},
       {q(r['model'])}, 'open', {r['users_max']}, {r['category']},
       {q(r['paper_floor'])}, {q(r['paper_wall'])}, {q(r['paper_landscape'])},
       {r['thickness_wall']}, {r['wall_height']}, {r['thickness_floor']},
       {q(r['moodlight_data'])}, {q(r['tags'])}, {q(r['allow_hidewall'])}
FROM catalog_bundle_repair_20261020 WHERE page_id = {page} AND room_id = 0;
SET @restored_bundle_room = IF(ROW_COUNT() = 1, LAST_INSERT_ID(), 0);
UPDATE catalog_bundle_repair_20261020 SET room_id = @restored_bundle_room
WHERE page_id = {page} AND room_id = 0 AND @restored_bundle_room > 0;

INSERT INTO items (user_id, room_id, item_id, wall_pos, x, y, z, rot, extra_data, wired_data, limited_data, guild_id)
SELECT @bundle_owner_id, b.room_id, i.id, s.wall_pos, s.x, s.y, s.z, s.rot, s.extra_data, '', '0:0', 0
FROM catalog_bundle_source_20261020 s
JOIN catalog_bundle_repair_20261020 b ON b.page_id = s.page_id
JOIN (SELECT item_name, MIN(id) id FROM items_base GROUP BY item_name) i ON i.item_name = s.item_name
WHERE b.page_id = {page} AND b.room_id > 0 AND b.items_restored = 0
  AND NOT EXISTS (SELECT 1 FROM items existing WHERE existing.room_id = b.room_id);

UPDATE catalog_bundle_repair_20261020 b SET items_restored = 1
WHERE b.page_id = {page} AND b.room_id > 0
  AND (SELECT COUNT(*) FROM items WHERE room_id = b.room_id) = {counts[old_room]};
UPDATE catalog_pages p JOIN catalog_bundle_repair_20261020 b ON b.page_id = p.id
SET p.room_id = b.room_id
WHERE p.id = {page} AND p.room_id = b.previous_room_id AND b.items_restored = 1;
UPDATE catalog_items c JOIN catalog_bundle_repair_20261020 b ON b.offer_id = c.id
JOIN catalog_pages p ON p.id = b.page_id AND p.room_id = b.room_id
SET c.item_ids = CAST((SELECT MIN(item_id) FROM items WHERE room_id = b.room_id) AS CHAR)
WHERE b.page_id = {page} AND b.items_restored = 1 AND c.item_ids = b.previous_item_ids;
""")
    sql.append("DROP TEMPORARY TABLE catalog_bundle_source_20261020;\n")
    return "\n".join(sql)


if __name__ == "__main__":
    TARGET.write_text(generate())
    print(TARGET)
